CREATE TABLE public.cargos (
  id uuid NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  empresa_id uuid NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  codigo text NOT NULL,
  nome text NOT NULL CHECK (char_length(nome) BETWEEN 1 AND 10),
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (empresa_id, codigo),
  UNIQUE (empresa_id, nome)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.cargos TO authenticated;
GRANT ALL ON public.cargos TO service_role;

ALTER TABLE public.cargos ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Admin gerencia cargos" ON public.cargos
  FOR ALL
  USING (empresa_id = get_user_empresa(auth.uid()) AND has_role(auth.uid(), 'admin'::app_role))
  WITH CHECK (empresa_id = get_user_empresa(auth.uid()) AND has_role(auth.uid(), 'admin'::app_role));

CREATE POLICY "Admin/Gerente veem cargos" ON public.cargos
  FOR SELECT
  USING (
    empresa_id = get_user_empresa(auth.uid())
    AND (has_role(auth.uid(), 'admin'::app_role) OR has_role(auth.uid(), 'gerente'::app_role))
  );

CREATE POLICY "Funcionario ve cargos ativos" ON public.cargos
  FOR SELECT
  USING (
    ativo = true
    AND EXISTS (
      SELECT 1
      FROM public.funcionarios f
      WHERE f.usuario_id = auth.uid()
        AND f.empresa_id = cargos.empresa_id
    )
  );

CREATE TRIGGER trg_cargos_updated
  BEFORE UPDATE ON public.cargos
  FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();

